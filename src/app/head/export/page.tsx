"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import Link from "next/link";
import { AlertTriangle, Download, FileSpreadsheet, FileText, Loader2, ShieldCheck, Star, WifiOff } from "lucide-react";
import { AppShell } from "@/components/app-shell";
import { InlineAlert } from "@/components/ui";
import { downloadExport } from "@/lib/api";
import { useApp } from "@/lib/store";

const TYPES = [
  {
    type: "summaries" as const,
    title: "Shift summaries",
    description: "One row per shift with timestamp-derived care minutes, completion and priority metrics.",
    columns: "shift_id, nurse_id, shift_type, started_at, ended_at, direct_care_min, indirect_care_min, interruption_min, emergency_min, completion_rate, tier12_on_time_rate, missed, deferred",
    icon: <FileSpreadsheet className="h-5 w-5" />,
  },
  {
    type: "events" as const,
    title: "Raw event log",
    description: "Append-only clinical-work events. This is the audit source for every summary and handover.",
    columns: "id, shift_id, bed_id, task_id, actor_id, type, client_ts, server_ts, payload",
    icon: <FileText className="h-5 w-5" />,
  },
  {
    type: "surveys" as const,
    title: "Survey responses",
    description: "SUS and raw TLX answers with participant code, phase and computed score.",
    columns: "id, participant_code, instrument, phase, score, taken_at, answers",
    icon: <Star className="h-5 w-5" />,
  },
  {
    type: "reviews" as const,
    title: "Manual reviews",
    description: "The five head-nurse ratings, comment and support flag. No computed overall score.",
    columns: "id, shift_id, nurse_id, reviewer_id, scores, comment, needs_support, created_at",
    icon: <ShieldCheck className="h-5 w-5" />,
  },
];

export default function ExportPage() {
  const router = useRouter();
  const user = useApp((s) => s.user);
  const token = useApp((s) => s.token);
  const online = useApp((s) => s.online);
  const notify = useApp((s) => s.notify);
  const [busy, setBusy] = useState<string | null>(null);

  useEffect(() => {
    if (user && user.role !== "head_nurse") router.replace("/beds");
    if (!user) router.replace("/login");
  }, [user, router]);

  async function download(type: "events" | "summaries" | "surveys" | "reviews") {
    if (!token) return;
    setBusy(type);
    try {
      const blob = await downloadExport(token, type);
      const url = URL.createObjectURL(blob);
      const anchor = document.createElement("a");
      anchor.href = url;
      anchor.download = `icu-tasklog-${type}.csv`;
      document.body.appendChild(anchor);
      anchor.click();
      anchor.remove();
      URL.revokeObjectURL(url);
      notify(`${type}.csv downloaded.`, "success");
    } catch (error) {
      notify(error instanceof Error ? error.message : "Download failed", "error");
    } finally {
      setBusy(null);
    }
  }

  if (!user) return null;

  return (
    <AppShell title="Export data" subtitle="CSV files for thesis analysis" activeOverride="/head/export">
      <div className="mx-auto max-w-4xl space-y-4">
        {!online ? (
          <InlineAlert tone="warning" title="Export needs a connection">
            <p>The head-nurse export is generated by the server. Reconnect to download.</p>
          </InlineAlert>
        ) : null}

        <InlineAlert tone="info" title="No patient identifiers are exported">
          <p>
            Exports contain staff participant codes, bed labels and free-text task titles. The UI warns users not to
            type patient identifiers, but rule-based checks cannot guarantee a free-text field is clean. Review
            before sharing.
          </p>
        </InlineAlert>

        <div className="grid gap-3 sm:grid-cols-2">
          {TYPES.map((item) => (
            <section key={item.type} className="card flex flex-col p-5">
              <span className="grid h-11 w-11 place-items-center rounded-xl bg-teal-50 text-teal-700">{item.icon}</span>
              <h2 className="mt-3 text-base font-bold text-ink">{item.title}</h2>
              <p className="mt-1 flex-1 text-xs leading-relaxed text-slate-500">{item.description}</p>
              <p className="mt-3 break-words rounded-lg bg-slate-50 p-2 font-mono text-[9px] leading-relaxed text-slate-400">
                {item.columns}
              </p>
              <button className="btn-primary mt-3" onClick={() => void download(item.type)} disabled={Boolean(busy) || !token}>
                {busy === item.type ? <Loader2 className="h-4 w-4 animate-spin" /> : <Download className="h-4 w-4" />}
                Download {item.type}.csv
              </button>
            </section>
          ))}
        </div>

        <div className="card p-5">
          <h2 className="flex items-center gap-2 text-sm font-bold text-ink"><AlertTriangle className="h-4 w-4 text-amber-500" /> Analysis notes</h2>
          <ul className="mt-3 space-y-2 text-xs leading-relaxed text-slate-600">
            <li>• Times are epoch milliseconds from the nurse device; the server adds its own receipt timestamp.</li>
            <li>• Durations are recomputed from events, so a corrected timestamp changes the derived duration.</li>
            <li>• Never average the five manual review criteria into a “nurse score”. Report each criterion separately.</li>
            <li>• Survey scores are computed with the standard SUS and unweighted raw-TLX formulas.</li>
            <li>• This is practice data from a thesis demo, not clinical evidence about real patients.</li>
          </ul>
        </div>

        <p className="text-center text-[11px] text-slate-400">
          Need the API docs? <Link href="/privacy" className="link">Privacy &amp; data</Link> explains storage and access.
        </p>
      </div>
    </AppShell>
  );
}
